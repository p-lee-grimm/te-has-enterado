#!/usr/bin/env bash
# Разбор нажатий: часто, отдельно от всего остального.
#
# Раз в две минуты, а не раз в полчаса: у callback_query короткий срок жизни,
# и ответ на просроченный Telegram уже не принимает — «query is too old».
# Для владельца это выглядит как мёртвая кнопка, ровно та жалоба, из-за
# которой кнопки и появились.
#
# Свой лок, не общий с publish: по нажатию «Завести» мы идём в Википедию и в
# модель, это десятки секунд. С общим локом медленная карточка задержала бы
# публикацию — второстепенное мешало бы главному.
#
# timeout — на случай зависшего HTTP: без него прогон держал бы лок вечно
# и кнопки перестали бы работать совсем.
set -u
source "$(dirname "${BASH_SOURCE[0]}")/_common.sh"
exec >>logs/callbacks.log 2>&1
lock callbacks
timeout 300 $PY run.py --process-callbacks
trim_log logs/callbacks.log
