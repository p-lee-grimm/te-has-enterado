-- Троттлинг сверки фактов (edits.py).
--
-- Пост в окне дописывания (autopost.edit_window_hours = 12ч) проверялся
-- каждые 30 минут независимо от того, появилось ли что-то новое —
-- до 24 запросов к модели за жизнь одного поста. Замер по логам: из 112
-- прогонов расхождение нашлось только в 33, и даже там — обычно на одном
-- посте из пяти. ~66% всех вызовов модели на VPS уходило на пустые сверки.
--
-- Теперь пост перепроверяется, только если у сюжета прибавилось статей
-- с прошлой проверки, либо прошло много времени без единой проверки —
-- это подстраховка на случай правки текста тем же изданием без новой
-- публикации. И то, и другое дешевле держать на самом посте, а не считать
-- заново каждый раз.
ALTER TABLE posts ADD COLUMN IF NOT EXISTS facts_checked_at TIMESTAMPTZ;
ALTER TABLE posts ADD COLUMN IF NOT EXISTS n_articles_at_check INTEGER;
