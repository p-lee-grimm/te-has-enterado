-- Каким провайдером и моделью посчитан вектор.
--
-- Векторы разных моделей лежат в разных пространствах: косинус между ними
-- ничего не значит. Если смешать их в одной таблице, кластеризация тихо
-- развалится — без ошибок, просто станет бессмысленной. Поэтому модель
-- пишется рядом с вектором, а несовпадение ловится явной проверкой.
ALTER TABLE articles ADD COLUMN IF NOT EXISTS embed_model TEXT;
CREATE INDEX IF NOT EXISTS articles_embed_model_idx ON articles (embed_model);
