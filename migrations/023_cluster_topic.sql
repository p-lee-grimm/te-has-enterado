-- Тема сюжета, определённая при генерации заголовка.
--
-- Нужна, чтобы не платить за модель дважды. Доли тем в канале ограничены
-- (autopost.topic_share), но тему сюжета знает только та же модель, что
-- пишет заголовок. Без этой колонки сюжет, отклонённый по квоте темы,
-- каждые полчаса заново прогонялся бы через генерацию — и каждые полчаса
-- заново отклонялся.
ALTER TABLE clusters ADD COLUMN IF NOT EXISTS topic TEXT;
